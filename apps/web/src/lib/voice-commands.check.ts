// Run: node apps/web/src/lib/voice-commands.check.ts
import assert from 'node:assert/strict';
import { parseVoiceCommand } from './voice-commands.ts';

assert.equal(parseVoiceCommand('go explore').kind, 'sync');
const takeExplore = parseVoiceCommand('take me to explore');
assert.equal(takeExplore.kind, 'sync');
if (takeExplore.kind === 'sync' && takeExplore.event.type === 'navigate') assert.equal(takeExplore.event.href, '/explore');
const openClassroom = parseVoiceCommand('open classroom');
assert.equal(openClassroom.kind, 'sync');
if (openClassroom.kind === 'sync' && openClassroom.event.type === 'navigate') assert.equal(openClassroom.event.href, '/classroom');
const solCmd = parseVoiceCommand('sol 420');
assert.equal(solCmd.kind, 'sync');
if (solCmd.kind === 'sync' && solCmd.event.type === 'explore.sol') assert.equal(solCmd.event.sol, 420);
assert.equal(parseVoiceCommand('classroom mode').kind, 'sync');
assert.equal(parseVoiceCommand('turn off voice').kind, 'power');
assert.equal(parseVoiceCommand('stop').kind, 'stop');
assert.equal(parseVoiceCommand('stop talking').kind, 'stop');
assert.equal(parseVoiceCommand('what can you do').kind, 'help');
assert.equal(parseVoiceCommand('ask why is Jezero interesting').kind, 'ask');
assert.equal(parseVoiceCommand('read risk').kind, 'sync');
assert.equal(parseVoiceCommand('export geojson').kind, 'sync');
assert.equal(parseVoiceCommand('what is science on Mars').kind, 'ask');
const route = parseVoiceCommand('show a route from landing to sol 400');
assert.equal(route.kind, 'ask', 'route requests go to the agent, not Home navigation or sol scrubbing');
assert.equal(parseVoiceCommand('draw a marswalk from the landing site to sol 700').kind, 'ask');
assert.equal(parseVoiceCommand('describe this screen').kind, 'describe');
assert.equal(parseVoiceCommand('what am I looking at').kind, 'describe');
const tl = parseVoiceCommand('open timeline');
assert.ok(tl.kind === 'sync' && tl.event.type === 'navigate' && tl.event.href === '/timeline');
const val = parseVoiceCommand('go to validation');
assert.ok(val.kind === 'sync' && val.event.type === 'navigate' && val.event.href === '/validation');
assert.equal(parseVoiceCommand('when is sunset at Jezero').kind, 'ask');
assert.equal(parseVoiceCommand('next conjunction blackout please').kind, 'ask', 'unknown phrases go to the agent');
assert.equal(parseVoiceCommand('hmm').kind, 'unknown');
assert.equal(parseVoiceCommand('suggest corridor').kind, 'sync');
assert.equal(parseVoiceCommand('Where was Perseverance on Sol 400?').kind, 'ask', 'a question about a sol is not a scrub command');
assert.equal(parseVoiceCommand('go to sol 420').kind, 'sync');
console.log('voice-commands checks passed');
